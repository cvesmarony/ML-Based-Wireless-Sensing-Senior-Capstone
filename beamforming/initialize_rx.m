    'Platform',          'B210', ...
    'SerialNum',         '3839223', ...
    'MasterClockRate',   30e6, ...
    'DecimationFactor',  30, ...
    'SamplesPerFrame',   TotalSamples, ...
    'CenterFrequency',   5.4e9, ...
    'ChannelMapping',    [1 2], ...
    'Gain',              [70 70], ...
    'OutputDataType',    'double');

disp('USRP initialized and ready for capture.');

